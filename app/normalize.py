# 单次扫描替换：每个位置只吃一次匹配，替换结果不再被后续规则二次处理
# （否则“拖欠工资”会被“欠工资”规则二次替换成“拖欠拖欠劳动报酬”）
_RULES = sorted(REPLACEMENTS, key=lambda kv: -len(kv[0]))
_RULE_RE = re.compile("|".join(re.escape(k) for k, _ in _RULES))
_RULE_MAP = dict(REPLACEMENTS)
# 长词优先；同长度按字面排序，避免 set 迭代顺序随哈希种子变化导致检索结果不稳定
_TERMS_BY_LEN = sorted(set(LEGAL_TERMS), key=lambda s: (-len(s), s))


def to_legal(text: str) -> str:
    """把口语表述替换为法言法语（用于检索与判定，不用于展示）。"""
    if not text:
        return ""
    return _RULE_RE.sub(lambda m: _RULE_MAP[m.group(0)], text)


def query_chars(text: str) -> list[str]:
    """抽取实义字符：去标点、去停用字，保序去重。

    retriever 与 agent 共用同一口径，避免“覆盖率按去重字符集、bigram 按未去重列表”
    两套口径打架。
    """
    seen: set[str] = set()
    out: list[str] = []
    for ch in re.findall(r"[一-龥A-Za-z0-9]", text or ""):
        if ch in STOP_CHARS or ch in seen:
            continue
        seen.add(ch)
        out.append(ch)
    return out


def legal_terms(text: str, limit: int = 10) -> list[str]:
    """从文本中抽出命中的领域法律词，长词优先，用于 FTS 精确召回。"""
    found = [t for t in _TERMS_BY_LEN if t in (text or "")]
    return found[:limit]


def term_vocab() -> list[str]:
    """全量领域词（长词优先），供检索侧统计文档频率。"""
    return _TERMS_BY_LEN


def expand_terms(text: str, limit: int = 6) -> list[str]:
    """口语词对应的法条表述，仅用于补充 FTS 召回（不参与覆盖率计算）。"""
    out: list[str] = []
    for key, vals in EXPANSIONS:
        if key in (text or ""):
            out.extend(vals)
    return list(dict.fromkeys(out))[:limit]


def bigram_hits(chars: list[str], content: str) -> int:
    """统计相邻实义字对在条文中连续出现的数量。"""
    return sum(1 for i in range(len(chars) - 1) if chars[i] + chars[i + 1] in content)
